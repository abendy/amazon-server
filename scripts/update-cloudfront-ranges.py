#!/usr/bin/env python3
"""Write the nginx list of CloudFront addresses whose X-Forwarded-For the RSVP site trusts.

    update-cloudfront-ranges.py [--check]

Reads AWS's published ranges and writes every CLOUDFRONT_ORIGIN_FACING prefix to
nginx/includes/cloudfront-real-ip.conf. Those are the addresses CloudFront, and so each
Lightsail distribution, uses to reach an origin. A request from any other address keeps its
own address, whatever X-Forwarded-For it sends.

--check writes nothing and exits 1 when the committed list differs from AWS's current one.
Commit a refreshed list, then converge staging and production.
"""

import argparse
import json
import sys
import urllib.request
from pathlib import Path
from typing import Any

RANGES_URL = "https://ip-ranges.amazonaws.com/ip-ranges.json"
SERVICE = "CLOUDFRONT_ORIGIN_FACING"
OUTPUT = Path(__file__).resolve().parent.parent / "nginx" / "includes" / "cloudfront-real-ip.conf"


def render(ranges: dict[str, Any]) -> str:
    """Return the include file for the given ip-ranges.json document."""
    ipv4 = sorted(
        (p["ip_prefix"] for p in ranges["prefixes"] if p["service"] == SERVICE),
        key=lambda prefix: tuple(int(part) for part in prefix.split("/")[0].split(".")),
    )
    ipv6 = sorted(p["ipv6_prefix"] for p in ranges["ipv6_prefixes"] if p["service"] == SERVICE)
    if not ipv4 or not ipv6:
        raise ValueError(f"{RANGES_URL} lists no {SERVICE} prefixes")

    lines = [
        "# Generated by scripts/update-cloudfront-ranges.py; do not edit by hand.",
        f"# Source: {RANGES_URL} service {SERVICE}",
        "#",
        "# Only CloudFront's own addresses may set the client address through",
        "# X-Forwarded-For. A request sent straight to the origin keeps its own address",
        "# whatever header it forges. CloudFront appends the viewer as the last entry;",
        "# real_ip_recursive skips any CloudFront hops after it.",
        "real_ip_header X-Forwarded-For;",
        "real_ip_recursive on;",
        "",
    ]
    lines += [f"set_real_ip_from {prefix};" for prefix in ipv4 + ipv6]
    return "\n".join(lines) + "\n"


def main() -> int:
    """Refresh or check the committed list."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report drift, write nothing")
    args = parser.parse_args()

    with urllib.request.urlopen(RANGES_URL, timeout=30) as response:
        ranges = json.load(response)
    wanted = render(ranges)
    current = OUTPUT.read_text() if OUTPUT.exists() else ""

    if wanted == current:
        print(f"{OUTPUT.name} is current.")
        return 0
    if args.check:
        print(f"{OUTPUT.name} differs from AWS's current {SERVICE} list.", file=sys.stderr)
        return 1

    OUTPUT.write_text(wanted)
    print(f"Wrote {OUTPUT.name}: {wanted.count('set_real_ip_from')} prefixes.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
